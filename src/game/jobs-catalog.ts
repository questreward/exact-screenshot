export function jobDetails(title: string) { return JOBS_CATALOG.find(j => j.title === title); }
export function jobRequirements(title: string): string[] {
 const j = jobDetails(title);
 return ["18 ans minimum", ...(j?.requirement ? [j.requirement] : []), ...(j?.license ? ["Permis de conduire"] : [])];
}
export function groupJobOffers<T extends {title: string}>(offers: T[]) {
 return Array.from(new Set(offers.map(o => jobDetails(o.title)?.category ?? "Autres métiers"))).sort().map(category => ({category, offers: offers.filter(o => (jobDetails(o.title)?.category ?? "Autres métiers") === category)}));
}
